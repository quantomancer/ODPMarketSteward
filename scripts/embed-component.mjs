import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const componentDirectory = path.join(repositoryRoot, "apps/component/dist");
const javascript = await readFile(
  path.join(componentDirectory, "component.js"),
  "utf8",
);
let css = "";
try {
  css = await readFile(path.join(componentDirectory, "component.css"), "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<style>${css.replaceAll("</style", "<\\/style")}</style>
</head>
<body>
<div id="root"></div>
<script>${javascript.replaceAll("</script", "<\\/script")}</script>
</body>
</html>`;

const output = `// Generated by scripts/embed-component.mjs. Do not edit manually.\nexport const componentHtml = ${JSON.stringify(html)};\n`;
await writeFile(
  path.join(repositoryRoot, "generated/component-resource.ts"),
  output,
  "utf8",
);
